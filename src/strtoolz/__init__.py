import itertools
import operator
import sys
from collections.abc import Iterator
from typing import SupportsIndex, TypeAlias, TypeVar

Bound: TypeAlias = SupportsIndex | None
Str = TypeVar("Str", str, bytes, bytearray)

__all__ = [
    'find_all',
    'find_iter',
    'find_nth',
    'index_nth',
    'partition_nth',
    'replace_counted',
    'replace_exactly',
    'replace_nth',
]

def find_all(s:Str, sub:Str, /, start:Bound=None, end:Bound=None) -> list[int]:
    """
    Return a list of all indexes in string s where substring sub is found,
    with no overlaps and all substrings contained within s[start:end].

    Optional arguments start and end are interpreted as in slice notation.
    """
    return list(find_iter(s, sub, start, end))


def find_iter(s:Str, sub:Str, /, start:Bound=None, end:Bound=None) -> Iterator[int]:
    """
    Yield all indexes in string s where substring sub is found,
    with no overlaps and all substrings contained within s[start:end].

    Optional arguments start and end are interpreted as in slice notation.
    """
    stride = max(1, len(sub))
    while 0 <= (start := s.find(sub, start, end)):
        yield start
        start += stride


def find_nth(s:Str, sub:Str, /, n:SupportsIndex, start:Bound=None, end:Bound=None) -> int:
    """
    Return the index of the nth non-overlapping occurrence of substring sub
    within s[start:end], otherwise -1.

      n
        Which occurrence of sub to search for, 0-based.

    Optional arguments start and end are interpreted as in slice notation.
    """
    n = operator.index(n)
    if not 0 <= n <= sys.maxsize:
        raise ValueError('n must be an integer 0 <= n <= sys.maxsize, got: {n}')
    it = find_iter(s, sub, start=start, end=end)
    return next(itertools.islice(it, n, None), -1)


def index_nth(s:Str, sub:Str, /, n:SupportsIndex, start:Bound=None, end:Bound=None) -> int:
    """
    Like find_nth(), but raise ValueError if the nth occurrence is not found.

      n
        Which occurrence of sub to search for, 0-based.

    Optional arguments start and end are interpreted as in slice notation.
    """
    idx = find_nth(s, sub, n=n, start=start, end=end)
    if idx < 0:
        raise ValueError('nth substring not found')
    return idx


def partition_nth(s:Str, sep:Str, /, n:SupportsIndex) -> tuple[Str, Str, Str]:
    """
    Split string s at the nth non-overlapping occurrence of sep, and return a
    3-tuple containing (part_before, sep, part_after).

      n
        Which occurrence of sub to search for, 0-based.

    If an nth occurrence is not found, return a 3-tuple
    (s, empty_string, empty_string).
    """
    if len(sep) == 0:
        raise ValueError('empty separator')

    idx = find_nth(s, sep, n=n)
    if idx < 0:
        empty_string = s[0:0]
        return (s, empty_string, empty_string)
    return (s[:idx], sep, s[idx+len(sep):])


def replace_counted(s:Str, old:Str, new:Str, /, count:SupportsIndex=-1) -> tuple[Str, int]:
    """
    Like s.replace() but return a 2-tuple (new_string, replacements_count).

    new_string is a copy of s with occurrences of substring old replaced by new.
    replacements_count is the number of replacements that were made.

      count
        Maximum number of occurrences to replace.
        -1 (the default value) means replace all occurrences.
    """
    if isinstance(s, str):
        if not isinstance(old, str):
            raise TypeError(f'argument 2 must be str, not {type(old)}')
        if not isinstance(new, str):
            raise TypeError(f'argument 3 must be str, not {type(new)}')
    elif isinstance(s, (bytes, bytearray)):
        if not isinstance(old, (bytes, bytearray)):
            raise TypeError(f'argument 2 must be bytes-like, not {type(old)}')
        if not isinstance(new, (bytes, bytearray)):
            raise TypeError(f'argument 3 must be bytes-like, not {type(new)}')
    else:
        raise TypeError(f'argument 1 must be str or bytes-like, not {type(s)}')

    count = operator.index(count)
    if not -sys.maxsize - 1 <= count <= sys.maxsize:
        # Error message generated by s.replace() varies by implementaion.
        # Possibly also by version, architecture, etc.
        raise OverflowError('int too large to convert')

    if len(s) < len(old):
        return (s, 0)

    if count < 0:
        count = sys.maxsize
    elif count == 0:
        return (s, 0)

    if len(old) == 0 == len(new):
        return (s, min(count, len(s) + 1))

    lwm = 0
    hwm = -1
    replacements_count = 0
    parts = []

    while replacements_count < count:
        hwm = s.find(old, lwm)
        if hwm == -1:
            break
        parts.append(s[lwm:hwm])
        parts.append(new)
        replacements_count += 1
        if len(old) == 0:
            parts.append(s[hwm:hwm+1])
            lwm = hwm + 1
        else:
            lwm = hwm + len(old)

    parts.append(s[lwm:])
    return (s[0:0].join(parts), replacements_count)


def replace_exactly(s:Str, old:Str, new:Str, /, count:SupportsIndex) -> Str:
    """
    Like s.replace() but replaces *exactly* count occurrences of old with new.

      count
        Exact number of occurrences to replace, count < 0 raises ValueError.

    If fewer than count occurrences of old are found in s, raise ValueError.
    """
    count = operator.index(count)
    if count < 0:
        raise ValueError(f'count must be >= 0, not {count}')

    new_s, replacements_count = replace_counted(s, old, new, count)
    if replacements_count < count:
        raise ValueError(
            f'Only {replacements_count} occurrences could be replaced, required '
            f'{count}',
        )
    return new_s


def replace_nth(s:Str, old:Str, new:Str, /, n:SupportsIndex) -> Str:
    """
    Return a copy of s with the nth non-overlapping occurrence of substring
    old replaced by new, otherwise raise ValueError.

      n
        Which occurrence of old to replace, 0-based.
    """
    idx = find_nth(s, old, n)
    if idx < 0:
        raise ValueError('nth occurrence of old substring not found')
    parts = [s[:idx], new, s[idx+len(old):]]
    return s[0:0].join(parts)
